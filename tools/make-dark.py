#!/usr/bin/env python3
"""Builds the dark theme from the light one: every colour in index.html's <style> gets a dark
counterpart (backgrounds go dark, text goes light, borders go subtle; brand blues and reds stay
recognisable), written between the DARK-THEME markers as rules under `html.dark`.
Run after changing the CSS:  python3 tools/make-dark.py   (needs: pip install tinycss2)"""
import colorsys, re, sys, tinycss2
from pathlib import Path

P = Path(__file__).resolve().parent.parent / "index.html"
html = P.read_text()
START, END = "/* DARK-THEME:START (generated by tools/make-dark.py, don't edit by hand) */", "/* DARK-THEME:END */"
light = re.search(r"<style>(.*?)</style>", html, re.S).group(1)
light = re.sub(re.escape(START) + r".*?" + re.escape(END), "", light, flags=re.S)

PAGE = "#0f1115"
HEX = re.compile(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})\b")
RGB = re.compile(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)")
NAMED = {"white": (255, 255, 255), "black": (0, 0, 0)}

def to_hex(r, g, b): return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, b))

def remap(rgb, kind):
    r, g, b = (v / 255 for v in rgb)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    neutral = s < 0.25 or l > 0.97 or l < 0.03
    if kind == "bg":
        if l > 0.6:   # light surfaces → dark surfaces (white cards a step lighter than the page)
            if neutral: l2, s2 = min(0.45, 0.14 + (1 - l) * 1.25), s * 0.3
            else: l2, s2 = min(0.30, 0.16 + (1 - l) * 0.8), min(s, 0.45)
        elif l < 0.25 and neutral: l2, s2 = 0.86 - l, s   # dark chips → light chips
        else: l2, s2 = l, s                               # brand colours (buttons) stay
    elif kind == "text":
        if neutral: l2, s2 = (1 - l * 0.9, s) if l < 0.6 else (l, s)
        else: l2, s2 = (max(l, 0.70), min(s, 0.85)) if l < 0.70 else (l, s)
    else:  # border / outline
        if l > 0.6: l2, s2 = min(0.42, 0.22 + (1 - l) * 0.8), s * 0.5
        elif neutral and l < 0.3: l2, s2 = 0.75, s
        else: l2, s2 = max(l, 0.55), s
    return to_hex(*colorsys.hls_to_rgb(h, l2, s2))

def remap_value(value, kind):
    def hx(m):
        v = m.group(1)
        if len(v) == 3: v = "".join(c * 2 for c in v)
        return remap(tuple(int(v[i:i + 2], 16) for i in (0, 2, 4)), kind)
    def rg(m):
        new = remap(tuple(int(m.group(i)) for i in (1, 2, 3)), kind)
        a = m.group(4)
        if a is None: return new
        r, g, b = (int(new[i:i + 2], 16) for i in (1, 3, 5))
        return "rgba(%d,%d,%d,%s)" % (r, g, b, a)
    out = HEX.sub(hx, value)
    out = RGB.sub(rg, out)
    out = re.sub(r"\b(white|black)\b", lambda m: remap(NAMED[m.group(1)], kind), out) if kind != "bg" or "url(" not in out else out
    return out

def kind_of(prop, sel):
    p = prop.lower()
    if p in ("background", "background-color", "background-image") or p in ("--bg", "--card", "--accent-soft"): return "bg"
    if p in ("color", "fill", "caret-color", "--ink", "--muted", "-webkit-text-fill-color", "text-decoration-color", "accent-color"): return "text"
    if p.startswith("border") or p.startswith("outline") or p in ("--line",): return "border"
    return None

def scope(sel):
    out = []
    for part in sel.split(","):
        s = part.strip()
        if not s: continue
        if s == ":root" or s == "html": out.append("html.dark")
        elif s.startswith("html"): out.append("html.dark" + s[4:])
        else: out.append("html.dark " + s)
    return ",".join(out)

def rules(nodes, out):
    for n in nodes:
        if n.type == "qualified-rule":
            sel = tinycss2.serialize(n.prelude).strip()
            decls = tinycss2.parse_declaration_list(n.content, skip_whitespace=True, skip_comments=True)
            body = []
            for d in decls:
                if d.type != "declaration": continue
                val = tinycss2.serialize(d.value).strip()
                k = kind_of(d.lower_name if not d.name.startswith("--") else d.name, sel)
                if not k or not (HEX.search(val) or RGB.search(val) or re.search(r"\b(white|black)\b", val)): continue
                if k == "bg" and (sel.strip() in ("body", "html", ":root") or d.name == "--bg"): new = re.sub(HEX, PAGE, val, count=1) if HEX.search(val) else val
                else: new = remap_value(val, k)
                if new != val: body.append(f"{d.name}:{new}{' !important' if d.important else ''}")
            if body: out.append(f"{scope(sel)}{{{';'.join(body)}}}")
        elif n.type == "at-rule" and n.lower_at_keyword == "media" and n.content:
            inner = []
            rules(tinycss2.parse_rule_list(n.content, skip_whitespace=True, skip_comments=True), inner)
            if inner: out.append(f"@media {tinycss2.serialize(n.prelude).strip()}{{{''.join(inner)}}}")

out = []
rules(tinycss2.parse_stylesheet(light, skip_whitespace=True, skip_comments=True), out)
# Inline styles in the page and in app.js templates
extra = [
  "html.dark{color-scheme:dark}",
  'html.dark [style*="color:#0a58ca"]{color:#7fb0ff!important}',
  'html.dark [style*="color:#666"],html.dark [style*="color:#555"]{color:#a3a6ad!important}',
  'html.dark [style*="background:#f4f5f7"]{background:#23262d!important}',
  'html.dark [style*="border:1px solid #d0d0d5"]{border-color:#3a3d45!important}',
  'html.dark [style*="background:#fff4d6"],html.dark [style*="background:#fff6d6"]{background:#3a2f12!important;color:#ffd98a!important}',
  'html.dark img.qrimg{background:#fff;padding:8px;border-radius:8px}',   # codes must stay black on white to scan
  'html.dark .barcode{background:#fff}',
]
block = START + "\n" + "\n".join(out + extra) + "\n" + END
new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, html, flags=re.S) if START in html else html.replace("</style>", block + "\n</style>", 1)
P.write_text(new)
print(f"dark rules: {len(out)} (+{len(extra)} extra)")
